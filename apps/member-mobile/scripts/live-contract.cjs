const assert = require('node:assert/strict');
const path = require('node:path');
const { ApiClient } = require(path.join(process.env.VINYRD_COMPILED_SERVICES, 'services/api.js'));
const { SessionController } = require(path.join(process.env.VINYRD_COMPILED_SERVICES, 'services/session.js'));
const { createServices } = require(path.join(process.env.VINYRD_COMPILED_SERVICES, 'services/endpoints.js'));
const { NetworkController } = require(path.join(process.env.VINYRD_COMPILED_SERVICES, 'services/networkState.js'));
async function main() {
  const base = process.env.VINYRD_LOCAL_TEST_API;
  assert(base.startsWith('http://127.0.0.1:'));
  const ids = JSON.parse(process.env.VINYRD_TEST_IDS);
  let stored = null;
  const storage = {read: async()=>stored,write:async token=>{stored=token;},remove:async()=>{stored=null;}};
  const api = new ApiClient(base, fetch, true);
  const session = new SessionController(api,storage);
  await session.restore();
  assert.equal(session.snapshot().status,'anonymous');
  await session.authenticate('register',{first_name:'Ada',last_name:'Person',email:'ada@test.local',password:'long-test-password'});
  const service = createServices(api);
  const network = new NetworkController(service);
  await network.refresh();
  assert.equal(network.snapshot().data.memberships.length,0);
  assert.equal(session.snapshot().status,'authenticated');
  const admins = {};
  for(const key of ['a','b']) {
    const client = new ApiClient(base,fetch,true);
    client.token=()=>ids['admin_'+key].Authorization.replace('Bearer ','');
    admins[key]=client;
    await client.request('/network/admin/profile',{method:'PUT',body:{name:'Church '+key,country:key==='a'?'TZ':'KE',city:key==='a'?'Arusha':'Nairobi',is_published:true}});
  }
  assert.equal((await service.discover({view:'tanzania'})).items.length,1);
  await service.follow(ids.a,true);
  await network.refresh();
  assert.deepEqual(network.snapshot().data.follows,[ids.a]);
  await assert.rejects(service.home(ids.a), e=>e.status===403);
  const request = await service.join(ids.a,'Please link my existing record',false);
  await assert.rejects(admins.b.request('/identity/requests/'+request.id+'/review',{method:'POST',body:{status:'approved'}}),e=>e.status===404);
  await admins.a.request('/identity/requests/'+request.id+'/review',{method:'POST',body:{status:'more_info_required',reason:'Verify your member record'}});
  await network.refresh();
  assert.equal(network.snapshot().data.requests[0].status,'more_info_required');
  await admins.a.request('/identity/requests/'+request.id+'/review',{method:'POST',body:{status:'approved',matched_member_id:ids.offline}});
  await network.refresh();
  assert.equal(network.snapshot().viewedChurchId,ids.a);
  assert.equal(network.snapshot().data.memberships[0].legacy_member_id,ids.offline);
  const second = await service.join(ids.b,'Second church',true);
  await admins.b.request('/identity/requests/'+second.id+'/review',{method:'POST',body:{status:'approved'}});
  await network.refresh();
  const b=network.snapshot().data.memberships.find(m=>m.church_id===ids.b);
  await network.setHome(b.id);
  network.selectChurch(ids.a);
  assert.equal((await service.network()).memberships.find(m=>m.is_primary).church_id,ids.b);
  assert.equal((await service.home(ids.b)).giving.total_amount,'0.00');
  assert.equal((await service.home(ids.a)).profile.name,'Ada Person');
  await Promise.all([service.events(ids.a),service.groups(ids.a),service.messages(ids.a),service.prayers(ids.a),service.sermons(ids.a),service.lessons(ids.a)]);
  await service.sendPrayer(ids.a,{body:'Please pray for my family',category:'family',visibility:'pastoral_team',allow_contact:false});
  assert.equal((await service.prayers(ids.a)).length,1);
  const profile=await service.profile();
  const {first_name,last_name,phone,avatar_url,country,region}=profile;
  await service.updateProfile({first_name,last_name,phone,avatar_url,country,region,city:'Arusha'});
  assert.equal((await service.profile()).city,'Arusha');
  await service.follow(ids.a,false);
  assert.deepEqual((await service.network()).follows,[]);
  const restored = new SessionController(new ApiClient(base,fetch,true),storage);
  await restored.restore();assert.equal(restored.snapshot().status,'authenticated');
  await restored.logout();assert.equal(stored,null);
  console.log('Live mobile service contract passed: register, restore, profile, zero membership, discovery, follow, request, more-info, legacy linking, second church, Home Church, context, private features, prayer, unfollow, logout, tenant denial.');
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
